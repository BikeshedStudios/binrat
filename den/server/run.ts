import { canonicalJson, sha256Hex } from "./canonical.ts";
import type { EvidenceModel, RecordRow } from "./evidence.ts";
import { appearancesOf, metadataFilled } from "./evidence.ts";
import { buildDossier, captureOf, caseSummary, shortAddress } from "./casefile.ts";

export type EmployStep = {
  id: "read" | "window" | "cross" | "file";
  label: string;
  detail: string;
};

export type EmployRun = {
  id: string;
  caseId: string;
  status: "COMPLETE";
  startedAt: string;
  completedAt: string;
  pacing: "PRESENTATION_ONLY";
  pacingNote: string;
  steps: EmployStep[];
  dossier: Awaited<ReturnType<typeof buildDossier>>;
  receiptPayload: Record<string, unknown>;
};

/**
 * The "employment" run is a deterministic local computation over the packaged evidence. Every
 * sentence in the steps is produced from the record; nothing is generated by a model, and no
 * network call is made.
 */
export async function runInvestigation(model: EvidenceModel, record: RecordRow, now: number) {
  const capture = captureOf(model, record);
  const summary = caseSummary(model, record);
  const appearances = appearancesOf(model, record.deployer);
  const windows = [...new Set(appearances.map((item) => item.captureId))];
  const filled = metadataFilled(record);
  const steps: EmployStep[] = [
    {
      id: "read",
      label: "READ THE SCRAP",
      detail: `Shapes checked: launchId ${record.launchId.slice(0, 10)}…, token ${record.token.slice(0, 10)}…, tx ${record.txHash.slice(0, 10)}…, fact ${record.factId}. Block ${record.blockNumber} ≤ checkpoint ${capture.checkpoint}.`,
    },
    {
      id: "window",
      label: "CHECK THE WINDOW",
      detail: `${capture.id} holds ${capture.recordCount} records ending at block ${capture.checkpoint}. This scrap is position ${record.position + 1}. Naming/social fields filled: ${filled} of 6.`,
    },
    {
      id: "cross",
      label: `CROSS-REFERENCE ${model.summary.recordCount} RECORDS`,
      detail: `Reported deployer ${shortAddress(record.deployer)} found in ${windows.length} of ${model.captures.length} captures (${appearances.length} record${appearances.length === 1 ? "" : "s"}). ${model.summary.uniqueDeployers} unique addresses were scanned.`,
    },
    {
      id: "file",
      label: "WRITE THE FILE",
      detail: `Findings are composed from recorded fields only. No name, identity, safety or outcome was inferred. The case digest is computed next to the receipts.`,
    },
  ];
  const dossier = await buildDossier(model, record);
  const receiptPayload = {
    kind: "BINRAT_EMPLOY_RUN",
    schemaVersion: "binrat.den.employ-receipt/1",
    product: "BINRAT: THE DEN",
    mode: "RECORDED_REPLAY",
    caseId: record.launchId,
    fileNumber: record.blockNumber,
    deployer: record.deployer,
    token: record.token,
    txHash: record.txHash,
    factId: record.factId,
    capture: {
      id: capture.id,
      checkpoint: capture.checkpoint,
      feedDigest: capture.feedDigest,
      readAt: capture.readAtIso,
      sourceKind: capture.source.kind,
      sourceFile: capture.source.file,
      sourceFileSha256: capture.source.fileSha256,
    },
    scan: {
      capturesScanned: model.captures.length,
      recordsScanned: model.summary.recordCount,
      uniqueDeployers: model.summary.uniqueDeployers,
      windowsWithAddress: windows.length,
      metadataFieldsFilled: filled,
    },
    caseDigest: dossier.digest.digest,
    findings: dossier.findings.map((finding) => ({ id: finding.id, kind: finding.kind, title: finding.title })),
    unknowns: dossier.unknowns.length,
    networkCalls: 0,
    liveCollector: false,
    issuedAt: new Date(now).toISOString(),
  };
  const receiptDigest = await sha256Hex(canonicalJson(receiptPayload));
  return {
    steps,
    dossier,
    receiptPayload,
    receiptDigest,
    run: {
      caseId: record.launchId,
      status: "COMPLETE" as const,
      startedAt: new Date(now).toISOString(),
      completedAt: new Date(now).toISOString(),
      pacing: "PRESENTATION_ONLY" as const,
      pacingNote:
        "Every step above is a real local lookup over the packaged records. The typing animation is presentation only; the run itself is computed before this response is sent.",
      stepCount: steps.length,
      scan: receiptPayload.scan,
      headline: dossier.headline,
      digest: dossier.digest.digest,
      receiptDigest,
    },
  };
}
